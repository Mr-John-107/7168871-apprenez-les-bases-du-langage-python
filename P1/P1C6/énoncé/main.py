# Création de la liste "fruits"
fruits = ["pomme","banane","orange"]
print(fruits)

# Ajout de kiwi à la liste
fruits.append("kiwi")
print(fruits)

# Suppression de "orange" de la liste
fruits.remove("orange")
print(fruits)

# Modification du deuxième élément de la liste "fruits" en "ananas"
fruits[1] = "ananas"
print(fruits)

# Affichage de la longueur
len(fruits)

# Tri de la liste "fruits" par ordre alphabétique
fruits.sort()
print(fruits)
